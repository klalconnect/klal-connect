export async function fillListingKitchens({ budgetMs = BUDGET_MS } = {}) {
  if ((await store.filter('Setting', { key: KEY })).length) return 0;
  const started = Date.now();
  const listings = new Map((await store.list('Provider')).map((p) => [p.id, p]));
  const todo = Object.entries(KITCHEN_FILL).flatMap(([kitchen, ids]) => ids
    .filter((id) => listings.has(id) && !listings.get(id).kitchen && listings.get(id).category === 'Food & Catering')
    .map((id) => ({ id, kitchen })));
  let filled = 0;
  for (let i = 0; i < todo.length; i += 10) {
    if (Date.now() - started > budgetMs) {
      console.log(`[listings] set the kitchen of ${filled} listings; ${todo.length - filled} left for the next start`);
      return filled;
    }
    const batch = todo.slice(i, i + 10);
    await Promise.all(batch.map(({ id, kitchen }) => store.update('Provider', id, kitchen === 'meat_dairy' ? { kitchen, kitchen_unconfirmed: true } : { kitchen })));
    filled += batch.length;
  }
  await store.create('Setting', { key: KEY, value: String(filled) });
  if (filled) console.log(`[listings] set the kitchen of ${filled} listings`);
  return filled;
}
