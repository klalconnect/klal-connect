// Rebuilds server/geo/worldCities.js: every town in the world of about a
// thousand people or more, so a location box can find "Deerfield Beach" or
// "Boise" with no geocoder key and no request to anyone.
//
//   npm i --no-save all-the-cities@3.1.0
//   node scripts/build-world-cities.mjs
//
// One line per town: name, country code, region, lat, lng, population. The
// region is only kept where people actually write it after a town's name (US
// states, Canadian provinces, Australian states); elsewhere the country says
// enough.
import fs from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

// GeoNames numbers Canadian and Australian regions; people use letters.
const CA = { '01': 'AB', '02': 'BC', '03': 'MB', '04': 'NB', '05': 'NL', '07': 'NS', '08': 'ON', '09': 'PE', '10': 'QC', '11': 'SK', '12': 'YT', '13': 'NT', '14': 'NU' };
const AU = { '01': 'ACT', '02': 'NSW', '03': 'NT', '04': 'QLD', '05': 'SA', '06': 'TAS', '07': 'VIC', '08': 'WA' };
const regionOf = (r) => (r.country === 'US' ? r.adminCode : r.country === 'CA' ? CA[r.adminCode] : r.country === 'AU' ? AU[r.adminCode] : '') || '';

const round = (n) => Math.round(n * 1000) / 1000;
const seen = new Set();
const lines = [];
const rows = [...require('all-the-cities')].sort((a, b) => b.population - a.population);
for (const r of rows) {
  const name = String(r.name || '').replace(/[\t\n]/g, ' ').trim();
  if (!name) continue;
  const region = regionOf(r);
  // The same name twice in one state is one town to anyone typing it; the
  // bigger one (first, by the sort) is the one they mean.
  const key = `${name.toLowerCase()}|${r.country}|${region}`;
  if (seen.has(key)) continue;
  seen.add(key);
  const [lng, lat] = r.loc.coordinates;
  lines.push([name, r.country, region, round(lat), round(lng), r.population].join('\t'));
}

fs.writeFileSync(new URL('../server/geo/worldCities.js', import.meta.url),
  '// Generated by scripts/build-world-cities.mjs from GeoNames (CC BY 4.0, via all-the-cities).\n'
  + '// name, country, region, lat, lng, population — one town per line, biggest first. Do not edit by hand.\n'
  + `export default ${JSON.stringify(lines.join('\n'))};\n`);
console.log(`${lines.length} towns`);
